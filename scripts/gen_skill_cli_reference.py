#!/usr/bin/env python3
"""Write the Ducta skill's CLI reference from the real argument parser.

The skill (``src/ducta/skills/ducta``) tells AI assistants which commands and
flags exist; written by hand, that list drifts from the code. This walks
``UnifiedArgumentParser`` and writes ``references/cli.md``. A test fails when
the file is not what this script would write.

Usage:
    python scripts/gen_skill_cli_reference.py            # write the file
    python scripts/gen_skill_cli_reference.py --check    # exit 1 if it is out of date
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Iterator, List, Tuple

# Run from a source checkout without installing the package first.
_SRC = Path(__file__).resolve().parent.parent / "src"
if _SRC.is_dir() and str(_SRC) not in sys.path:
    sys.path.insert(0, str(_SRC))

TARGET = _SRC / "ducta" / "skills" / "ducta" / "references" / "cli.md"

HEADER = """\
# Ducta CLI reference

<!-- Generated by scripts/gen_skill_cli_reference.py from the real argument parser.
     Do not edit by hand: run the script again after changing a command. -->

Every command and option of the `ducta` CLI. For the full text of one command,
run `ducta <command> --help`. Options marked *(required)* must be given.

## Contents
"""


def _subcommands(parser: argparse.ArgumentParser) -> List[Tuple[str, str, argparse.ArgumentParser]]:
    """(name, help, parser) of each subcommand, aliases left out."""
    out = []
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            helps = {a.dest: a.help or "" for a in action._choices_actions}
            seen = set()
            for name, sub in action.choices.items():
                if id(sub) in seen:
                    continue
                seen.add(id(sub))
                out.append((name, helps.get(name, ""), sub))
    return out


def walk(
    parser: argparse.ArgumentParser, path: Tuple[str, ...] = ("ducta",)
) -> Iterator[Tuple[Tuple[str, ...], str, argparse.ArgumentParser]]:
    for name, help_text, sub in _subcommands(parser):
        yield (*path, name), help_text, sub
        yield from walk(sub, (*path, name))


def _clean(text: str) -> str:
    text = re.sub(r"\s+", " ", (text or "").replace("%(default)s", "")).strip()
    return text.replace("|", "\\|")


def _options(parser: argparse.ArgumentParser) -> List[str]:
    rows = []
    for action in parser._actions:
        if isinstance(action, (argparse._HelpAction, argparse._SubParsersAction)):
            continue
        if action.help == argparse.SUPPRESS:
            continue
        if action.option_strings:
            name = ", ".join(f"`{o}`" for o in action.option_strings)
        else:
            name = f"`<{action.dest}>`"
        notes = []
        if action.choices and not isinstance(action.choices, dict):
            notes.append("one of " + ", ".join(f"`{c}`" for c in action.choices))
        if action.required:
            notes.append("*(required)*")
        default = action.default
        if (
            action.option_strings
            and default not in (None, False, argparse.SUPPRESS)
            and not isinstance(default, (list, dict))
        ):
            notes.append(f"default `{default}`")
        text = _clean(action.help or "")
        rows.append(f"| {name} | {text}{' — ' if text and notes else ''}{'; '.join(notes)} |")
    return rows


def render() -> str:
    from ducta.console.parser import UnifiedArgumentParser

    root = UnifiedArgumentParser.create()
    commands = list(walk(root))
    lines = [HEADER]
    for path, _, _ in commands:
        if len(path) == 2:
            lines.append(f"- [`{' '.join(path)}`](#{'-'.join(path)})")
    lines.append("")
    for path, help_text, parser in commands:
        level = "#" * min(len(path), 4)
        lines.append(f"{level} {' '.join(path)}")
        lines.append("")
        description = _clean(parser.description or help_text)
        if description:
            lines.append(description)
            lines.append("")
        options = _options(parser)
        if options:
            lines += ["| Option | What it does |", "|---|---|", *options, ""]
    return "\n".join(lines).rstrip() + "\n"


def main(argv: List[str]) -> int:
    text = render()
    if "--check" in argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != text:
            print(f"{TARGET} is out of date: run python scripts/gen_skill_cli_reference.py")
            return 1
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text, encoding="utf-8")
    print(f"Wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
